// Pushes src/ with clasp and points the web app deployment at the new code.
// Secrets live in the git-ignored .env and are written into src/Secrets.gs (also git-ignored) on every deploy.
// The first run creates the tokens and the web app deployment and saves them to .env.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ENV = path.join(ROOT, '.env');

const env = fs.existsSync(ENV)
  ? Object.fromEntries(fs.readFileSync(ENV, 'utf8').split(/\r?\n/).filter(l => /^\w+=/.test(l))
    .map(l => [l.split('=')[0], l.slice(l.indexOf('=') + 1).trim()]))
  : {};

function save() {
  fs.writeFileSync(ENV, Object.entries(env).map(([k, v]) => `${k}=${v}`).join('\n') + '\n');
  fs.writeFileSync(path.join(ROOT, 'src', 'Secrets.gs'), '// Generated by tools/deploy.mjs from .env. Do not commit.\n' +
    'const SECRETS = ' + JSON.stringify({
      RUN_TOKEN: env.RUN_TOKEN, FEEDBACK_SECRET: env.FEEDBACK_SECRET, WEBAPP_URL: env.WEBAPP_URL || '',
    }, null, 2) + ';\n');
}

const run = cmd => execSync(cmd, { cwd: ROOT, stdio: 'inherit' });

for (const k of ['RUN_TOKEN', 'FEEDBACK_SECRET']) env[k] = env[k] || crypto.randomBytes(18).toString('hex');
save();
run('clasp push --force');
if (!env.DEPLOYMENT_ID) {
  const out = execSync('clasp create-deployment --description "web app"', { cwd: ROOT, encoding: 'utf8' });
  const id = (out.match(/AKfy[\w-]+/) || [])[0];
  if (!id) throw new Error('No deployment id in clasp output: ' + out);
  env.DEPLOYMENT_ID = id;
  env.WEBAPP_URL = `https://script.google.com/macros/s/${id}/exec`;
  save();
  run('clasp push --force');
}
run(`clasp update-deployment ${env.DEPLOYMENT_ID} --description "deploy ${new Date().toISOString()}"`);
console.log('Web app:', env.WEBAPP_URL);
